import clsx from "clsx"
import type { ReactNode } from "react"

import { CopyButton } from "@/components/CopyButton"
import { SaveQrButton } from "@/components/SaveQrButton"
import { formatVnd } from "@/lib/format"

function Row({
  label,
  value,
  copy,
  copyName,
  emphasis,
}: {
  label: string
  value: string
  copy?: string
  /** What the copy button copies, for screen readers ("số tài khoản"). */
  copyName?: string
  /** The transfer content: tinted and set in mono, since a wrong one cannot be matched. */
  emphasis?: boolean
}) {
  return (
    <div className={clsx("py-3", emphasis && "mt-2 rounded-md bg-warning-soft px-3")}>
      <dt className={clsx("text-sm", emphasis ? "font-semibold text-fg" : "text-muted")}>{label}</dt>
      <dd className="mt-1 flex items-center justify-between gap-3">
        <span className={clsx("min-w-0 font-semibold break-all text-fg", emphasis && "font-mono text-h3")}>
          {value}
        </span>
        {copy !== undefined && <CopyButton value={copy} name={copyName} />}
      </dd>
    </div>
  )
}

/**
 * The payment instructions of a donation or a pledge (DOS/Give#96): the
 * VietQR code with a save button, and the same details to copy one by one
 * for banking apps that cannot scan. `svg` is generated by the page from
 * the payment payload, never taken from input.
 */
export function TransferDetails({
  svg,
  filename,
  qrCaption,
  bankBin,
  accountNumber,
  accountName,
  amount,
  reference,
  footnote,
}: {
  svg: string
  filename: string
  qrCaption: ReactNode
  bankBin: string
  accountNumber: string
  accountName: string
  amount: number
  reference: string
  footnote: ReactNode
}) {
  return (
    <section aria-labelledby="transfer-title" className="card">
      <div className="border-b border-border p-4 sm:px-6">
        <h2 id="transfer-title" className="text-h2">
          Chuyển khoản bằng VietQR
        </h2>
        <p className="mt-1 text-fg">Quét mã bằng app ngân hàng, hoặc chép từng thông tin bên dưới.</p>
      </div>
      <div className="grid gap-6 p-4 sm:p-6 md:grid-cols-[15rem_minmax(0,1fr)] md:gap-8">
        <div className="min-w-0 text-center">
          {/* The SVG draws its own white background and quiet zone, so it scans in the dark theme too. */}
          <div
            className="mx-auto w-full max-w-60 overflow-hidden rounded [&>svg]:h-auto [&>svg]:w-full"
            role="img"
            aria-label="Mã VietQR để chuyển khoản"
            // The SVG is generated by the page from the payload, not taken from input.
            dangerouslySetInnerHTML={{ __html: svg }}
          />
          <p className="mt-3 text-sm text-muted">{qrCaption}</p>
          <SaveQrButton svg={svg} filename={filename} />
        </div>
        <div className="min-w-0">
          <dl className="divide-y divide-border">
            <Row label="Mã ngân hàng (BIN)" value={bankBin} />
            <Row label="Số tài khoản" value={accountNumber} copy={accountNumber} copyName="số tài khoản" />
            <Row label="Chủ tài khoản" value={accountName} />
            <Row label="Số tiền" value={formatVnd(amount)} copy={String(amount)} copyName="số tiền" />
            <Row
              label="Nội dung chuyển khoản"
              value={reference}
              copy={reference}
              copyName="nội dung chuyển khoản"
              emphasis
            />
          </dl>
          <p className="mt-4 text-fg">{footnote}</p>
        </div>
      </div>
    </section>
  )
}
